"""Write the site map with a migrated / not-migrated status for every known page, document, hub and
portal: document 396 pages in navigation order (from the exported navigation) plus the statuses kept
in docs/tui-brandhub/site-status.json (edit statuses there, then re-run).
Usage: python3 -I write_sitemap.py <navigation.json> <site-status.json> <out.md>
"""
import json
import sys

nav = json.load(open(sys.argv[1]))['data']
st = json.load(open(sys.argv[2]))
d = st['document_396']
L = [f"# Site map and migration status (status updated {st['updated']})", '',
     f"Generated by `tools/frontify-export/write_sitemap.py` from `{sys.argv[1]}` and `{sys.argv[2]}`. Edit statuses in the JSON, not here.",
     f"Surfaces: {st['surfaces_legend']}. {st['branch_note']}", '',
     '## Summary', '',
     '| Item | Status |', '|---|---|',
     f"| Document 396 \"{d['title']}\" (portal {d['portal']}), all pages + {len(d['chrome'])} chrome documents | migrated; see the page table |"]
for h in st['migrated_hubs']:
    what = f"Portal {h['portal']}" + (' document' if 'document' in h['title'].lower() else ' home')
    L.append(f"| {what} \"{h['title']}\" (`{'`, `'.join(h['paths'])}`) | {h['status']} |")
L.append(f"| {len(st['not_migrated'])} other Frontify targets linked from the migrated pages | not migrated (out of scope); see the last table |")
L += ['', '## Portals', '', '| Portal | Title | Home | Documents |', '|---|---|---|---|']
for p in st['portals']:
    L.append(f"| {p['portal']} | {p['title']} | {p['home']} | {p['documents']} |")

L += ['', f"## Document 396 pages", '',
      'Order = Frontify navigation order = pagination order. Path = migrated EDS path. H = page headings (sidebar anchors).',
      f"Status unless noted: {d['default_status']}.", '',
      '| # | page id | path | title | H | status |', '|---|---|---|---|---|---|']
n = 0
for c in nav:
    t = c['translations']['default']
    if c['type'] == 'page_category':
        L.append(f"| | | **{t['title']}** (category {c['id']}, slug `{t['slug']}`) | | | |")
        kids = [k for k in c.get('children', []) if k['type'] == 'page']
    else:
        kids = [c]
        t = {'slug': None}
    for k in kids:
        n += 1
        kt = k['translations']['default']
        path = f"/{t['slug']}/{kt['slug']}" if t.get('slug') else f"/{kt['slug']}"
        heads = sum(1 for h in k.get('children', []) if h['type'] == 'page_heading')
        status = d['published'].get(path, d['default_row'])
        L.append(f"| {n} | {k['id']} | `{path}` | {kt['title'] or '(untitled, hidden in sidebar)'} | {heads} | {status} |")
L += ['', f'{n} pages.', '', f"Chrome documents ({d['chrome_status']}):", '']
L += [f"- `{p}`: {what}" for p, what in d['chrome'].items()]

L += ['', '## Not migrated: Frontify targets linked from migrated pages', '',
      'All stay absolute links to the resolved Frontify URL (never `/r/`). "Linked from" counts links in document 396 / the portal 162 home / the homepage (portal 161).',
      'A "hub" id is taken to be a portal id (`/hub/<id>` = that portal\'s home; verified only for 162).', '',
      '| Kind | Id | Title | Title source | In portal navigation | Linked from 396 / 162 / 161 | URLs linked |', '|---|---|---|---|---|---|---|']
for o in st['not_migrated']:
    urls = '<br>'.join(f"`{u.replace('https://tui-brandhub.com', '')}`" for u in o['urls'])
    L.append(f"| {o['kind']} | {o['id']} | {o['title']} | {o['title_source']} | {o.get('in_portal_nav', '')} | "
             f"{o['linked_from_doc396']} / {o['linked_from_hub162']} / {o.get('linked_from_hub161', 0)} | {urls} |")
L += ['', 'Not listed: the header "Brand Assistant" link on document 396 pages points back at `/document/396` on Frontify on purpose (the AI assistant is not migrated).']
open(sys.argv[3], 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(n, 'pages,', len(st['not_migrated']), 'not-migrated targets written to', sys.argv[3])

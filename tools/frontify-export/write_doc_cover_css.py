"""Write styles/doc-cover.css: the generic port of Frontify's new document theme (cover pages):
section region/grid and the text styles, all read from Frontify's --f-theme-settings-* variables
(set per colour scheme by the theme file). Re-run after changing this generator.
Usage: python3 -I write_doc_cover_css.py <out.css>
"""
import sys

PROPS = ['font-family', 'font-size', 'font-weight', 'font-style', 'line-height', 'letter-spacing',
         'text-transform', 'text-decoration', 'color', 'margin-top', 'margin-bottom']
# Frontify text style -> selectors (the importer marks each element with its style as a class)
# (text cells carry the style as a class; image titles/captions use the converter's tags:
# heading1-4 -> h1-h4, custom1/2 -> h5/h6, quote -> blockquote)
STYLES = {
    'heading1': ['.text .heading1', '.image figcaption h1'], 'heading2': ['.text .heading2', '.image figcaption h2'],
    'heading3': ['.text .heading3', '.image figcaption h3'], 'heading4': ['.text .heading4', '.image figcaption h4'],
    'custom1': ['.text .custom1', '.image figcaption h5'], 'custom2': ['.text .custom2', '.image figcaption h6'],
    'custom3': ['.text .custom3'],
    # the content pipeline wraps quote text in <p> inside the blockquote: style both
    'quote': ['.text blockquote', '.text blockquote p', '.image figcaption blockquote', '.image figcaption blockquote p'],
    # image title/caption styles (Frontify imageTitle/imageCaption elements of Image titles and
    # captions; the importer marks them image-title-text / image-caption-text)
    'image-title': ['.image figcaption .image-title-text'],
    'image-caption': ['.image figcaption .image-caption-text'],
}


def rule(selectors, style, props=PROPS):
    sel = ',\n'.join(f'.doc-sections main {s}' for s in selectors)
    body = '\n'.join(f'  {p}: var(--f-theme-settings-{style}-{p});' for p in props)
    # Frontify text elements break long words (tw-break-words) instead of overflowing
    return f'{sel} {{\n{body}\n  overflow-wrap: break-word;\n}}'


